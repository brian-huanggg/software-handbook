-- SQL Bootcamp schema (PostgreSQL 16)
-- 重複執行安全：會先刪除舊表。
-- 刻意不建立 FK 以外的額外 index，index 相關題目（Q75 起）才會教。

DROP TABLE IF EXISTS payments    CASCADE;
DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS orders      CASCADE;
DROP TABLE IF EXISTS products    CASCADE;
DROP TABLE IF EXISTS categories  CASCADE;
DROP TABLE IF EXISTS customers   CASCADE;
DROP TABLE IF EXISTS employees   CASCADE;

-- 員工：manager_id 自我參照，用於 self join 與遞迴 CTE
CREATE TABLE employees (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text           NOT NULL,
    title       text           NOT NULL,
    department  text           NOT NULL,
    manager_id  integer        REFERENCES employees (id),
    salary      numeric(10, 2) NOT NULL CHECK (salary > 0),
    hired_at    date           NOT NULL
);

-- 顧客：phone 可為 NULL，referred_by 為推薦人
CREATE TABLE customers (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text        NOT NULL,
    email        text        NOT NULL UNIQUE,
    phone        text,
    city         text        NOT NULL,
    country      text        NOT NULL,
    birth_date   date,
    referred_by  integer     REFERENCES customers (id),
    created_at   timestamptz NOT NULL DEFAULT now()
);

-- 分類：parent_id 自我參照，形成分類樹
CREATE TABLE categories (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       text    NOT NULL,
    parent_id  integer REFERENCES categories (id)
);

CREATE TABLE products (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          text           NOT NULL,
    category_id   integer        NOT NULL REFERENCES categories (id),
    price         numeric(10, 2) NOT NULL CHECK (price >= 0),
    stock         integer        NOT NULL DEFAULT 0 CHECK (stock >= 0),
    discontinued  boolean        NOT NULL DEFAULT false,
    created_at    timestamptz    NOT NULL DEFAULT now()
);

-- 訂單：employee_id 為負責業務，線上訂單為 NULL
CREATE TABLE orders (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  integer     NOT NULL REFERENCES customers (id),
    employee_id  integer     REFERENCES employees (id),
    status       text        NOT NULL
                 CHECK (status IN ('pending', 'shipped', 'completed', 'cancelled')),
    ordered_at   timestamptz NOT NULL,
    shipped_at   timestamptz
);

-- 訂單明細：unit_price 為下單當時的價格，可能與 products.price 不同
CREATE TABLE order_items (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    integer        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    product_id  integer        NOT NULL REFERENCES products (id),
    quantity    integer        NOT NULL CHECK (quantity > 0),
    unit_price  numeric(10, 2) NOT NULL CHECK (unit_price >= 0),
    UNIQUE (order_id, product_id)
);

-- 付款：一張訂單可能分多次付款，也可能完全沒有付款
CREATE TABLE payments (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id  integer        NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    amount    numeric(10, 2) NOT NULL CHECK (amount > 0),
    method    text           NOT NULL
              CHECK (method IN ('credit_card', 'bank_transfer', 'cash_on_delivery')),
    paid_at   timestamptz    NOT NULL
);
