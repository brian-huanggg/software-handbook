import { existsSync, readdirSync } from 'node:fs';

/** One section, e.g. `{ label: '2.3 快取', dir: '2-3-cache' }`. */
export interface Section {
	label: string;
	dir: string;
}

/** One level, e.g. L2, holding its sections in reading order. */
export interface Level {
	label: string;
	dir: string;
	sections: Section[];
}

const contentRoot = new URL('../content/docs/', import.meta.url);

// A section directory counts only once it holds at least one article. This keeps
// unwritten sections out of the sidebar instead of showing them as empty groups.
function hasArticles(path: string): boolean {
	const dir = new URL(`${path}/`, contentRoot);
	if (!existsSync(dir)) return false;
	return readdirSync(dir, { recursive: true }).some((f) => /\.mdx?$/.test(String(f)));
}

/**
 * Builds a field's sidebar: hand-written level and section labels (so readers
 * see "2.3 快取" rather than the directory name), with articles inside each
 * section autogenerated and ordered by their `sidebar.order` frontmatter.
 *
 * The config is evaluated when the dev server starts, so a newly created
 * section directory appears after a restart.
 */
export function fieldSidebar(field: string, levels: Level[]) {
	return levels
		.map((level) => ({
			label: level.label,
			collapsed: true,
			items: level.sections
				.filter((s) => hasArticles(`${field}/${level.dir}/${s.dir}`))
				.map((s) => ({
					label: s.label,
					collapsed: true,
					items: [{ autogenerate: { directory: `${field}/${level.dir}/${s.dir}` } }],
				})),
		}))
		.filter((level) => level.items.length > 0);
}
